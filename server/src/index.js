import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { connectDB } from './config/db.js';
import api from './routes/api.js';
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.use('/api/public/inquiries',rateLimit({windowMs:15*60*1000,max:20,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({status:'ok'}));
app.use('/api',api);
app.use((err,req,res,next)=>{console.error(err);if(err.name==='ValidationError')return res.status(400).json({message:'Please check the submitted fields.'});if(err.code===11000)return res.status(409).json({message:'A record with that value already exists.'});res.status(500).json({message:'Something went wrong. Please try again.'})});
const port=Number(process.env.PORT||5000);
connectDB().then(()=>app.listen(port,()=>console.log(`API listening on ${port}`))).catch(err=>{console.error('Startup failed:',err.message);process.exit(1)});
